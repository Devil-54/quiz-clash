/**
 * Generates a random English Grammar question filtered by difficulty with shuffled options.
 * Ensures no duplicate questions within the same match.
 * @param {Set<number|string>} [usedIndices] - Set of already used question indices/IDs
 * @param {string} [difficulty="medium"] - "easy" | "medium" | "hard"
 * @returns {Object} Grammar Question object
 */
export function generateGrammarQuestion(usedIndices = new Set(), difficulty = "medium") {
  const normDiff = String(difficulty || "medium").toLowerCase();

  // Filter questions matching the requested difficulty
  const matchingIndices = [];
  for (let i = 0; i < GRAMMAR_QUESTIONS.length; i++) {
    const q = GRAMMAR_QUESTIONS[i];
    if (q.difficulty.toLowerCase() === normDiff) {
      matchingIndices.push(i);
    }
  }

  // Fallback if matching pool is empty for unexpected reason
  const candidateIndices = matchingIndices.length > 0
    ? matchingIndices
    : Array.from({ length: GRAMMAR_QUESTIONS.length }, (_, i) => i);

  const available = candidateIndices.filter((idx) => !usedIndices.has(idx));
  const pool = available.length > 0 ? available : candidateIndices;

  const selectedIndex = pool[Math.floor(Math.random() * pool.length)];
  usedIndices.add(selectedIndex);

  const raw = GRAMMAR_QUESTIONS[selectedIndex];

  // Shuffle options
  const shuffledOptions = [...raw.options];
  for (let i = shuffledOptions.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffledOptions[i], shuffledOptions[j]] = [shuffledOptions[j], shuffledOptions[i]];
  }

  const diffLabel = raw.difficulty || (normDiff === "hard" ? "Hard" : normDiff === "easy" ? "Easy" : "Medium");

  return {
    id: `grammar-${Date.now()}-${Math.floor(Math.random() * 9000 + 1000)}`,
    text: raw.text,
    question: raw.text,
    options: shuffledOptions,
    correct: raw.correct,
    category: raw.category || "📚 English Grammar",
    difficulty: diffLabel,
    mode: "grammar",
  };
}
